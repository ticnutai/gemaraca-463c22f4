-- פסק זמן לעסקה שנתקעה באוויר
-- ─────────────────────────────────────────────────────────────
-- היום המסד לא ענה במשך כחצי שעה והוצרך להפעלה מחדש. האבחון שלאחר מכן
-- שלל את החשודים הרגילים — 27 חיבורים מתוך 60, אפס עסקאות תלויות, אפס
-- שאילתות ארוכות — אבל חשף הגדרה מסוכנת:
--
--   idle_in_transaction_session_timeout = 0
--
-- אפס פירושו כבוי. עסקה שנפתחה ונתקעה — לקוח שקרס, רשת שנותקה, סקריפט
-- שנעצר באמצע — מחזיקה את הנעילות שלה **לנצח**, וכל מי שצריך את אותן
-- שורות ממתין לה בלי סוף. זו אחת הדרכים הנפוצות שבהן מסד נראה "תקוע".
--
-- חמש דקות הן ארוכות הרבה מעבר לכל עסקה לגיטימית אצלנו: הכתיבות הכבדות
-- ביותר שלנו עובדות במנות של 200–500 שורות ונסגרות בשניות. מנגד הן קצרות
-- מספיק כדי שעסקה שנשכחה תשוחרר לפני שהיא עוצרת את האפליקציה.
--
-- `statement_timeout` כבר עומד על שתי דקות ואינו משתנה כאן.

ALTER DATABASE postgres SET idle_in_transaction_session_timeout = '5min';

-- ההגדרה למעלה חלה על חיבורים חדשים בלבד. התפקידים שהאפליקציה מתחברת
-- בהם מקבלים אותה מיד, כדי שלא נמתין לסבב חיבורים.
ALTER ROLE authenticator SET idle_in_transaction_session_timeout = '5min';
ALTER ROLE anon          SET idle_in_transaction_session_timeout = '5min';
ALTER ROLE authenticated SET idle_in_transaction_session_timeout = '5min';
